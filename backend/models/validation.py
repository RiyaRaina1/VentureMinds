"""
VentureMind AI — Phase 3A
SQLAlchemy model for persisting AI-generated validation reports.
"""
import json
from datetime import datetime
from sqlalchemy import Column, Integer, String, Text, DateTime, Float, ForeignKey
from sqlalchemy.orm import relationship
from backend.database.connection import Base


class ValidationReport(Base):
    """
    Stores a single startup validation analysis generated by the AI engine.
    - report_data stores the full structured JSON response as a text column.
    - score stores the computed aggregate validation score (0-100).
    - status: 'completed', 'failed', 'partial'
    - report_type: 'startup_validation' (extensible for future engine types)
    """
    __tablename__ = "validation_reports"

    id = Column(Integer, primary_key=True, index=True, autoincrement=True)
    startup_id = Column(
        Integer,
        ForeignKey("startups.id", ondelete="SET NULL"),
        nullable=True,
        index=True
    )
    report_type = Column(String(100), nullable=False, default="startup_validation")
    status = Column(String(50), nullable=False, default="completed")
    score = Column(Float, nullable=True)
    report_data = Column(Text, nullable=False)  # JSON stored as text
    input_summary = Column(Text, nullable=True)  # Truncated input for display
    model_used = Column(String(100), nullable=True)
    created_at = Column(DateTime, default=datetime.utcnow, nullable=False)

    # Optional relationship back to Startup
    startup = relationship("Startup", backref="validation_reports")

    def get_report_dict(self) -> dict:
        """Deserialize report_data JSON safely."""
        try:
            return json.loads(self.report_data)
        except (json.JSONDecodeError, TypeError):
            return {}

    def __repr__(self):
        return (
            f"<ValidationReport(id={self.id}, startup_id={self.startup_id}, "
            f"score={self.score}, status='{self.status}')>"
        )
